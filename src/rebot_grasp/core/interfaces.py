"""Ports depend only on NumPy and project-owned types."""

from typing import Protocol

import numpy as np

from .types import GraspCandidate, GraspPlan, RGBDFrame, Target


class Camera(Protocol):
    def open(self) -> None: ...
    def capture(self) -> RGBDFrame: ...
    def close(self) -> None: ...


class Detector(Protocol):
    def detect(self, frame: RGBDFrame) -> list[Target]: ...


class GraspBackend(Protocol):
    def predict(self, frame: RGBDFrame, target: Target | None) -> list[GraspCandidate]: ...


class Robot(Protocol):
    def tcp_pose(self) -> np.ndarray: ...
    def reachable(self, T_base_tcp: np.ndarray) -> bool: ...
    def move(self, T_base_tcp: np.ndarray, duration_s: float) -> bool: ...
    def open_gripper(self, width_m: float) -> None: ...
    def close_gripper(self) -> bool: ...


class PathValidator(Protocol):
    """Validate current-pose-to-plan transitions, limits and collisions."""
    def validate(self, robot: Robot, plan: GraspPlan) -> bool: ...
